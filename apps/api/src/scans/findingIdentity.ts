import { createHash } from 'node:crypto';
import { FINDING_TEXT_MAX_LENGTH, FINDING_TITLE_MAX_LENGTH, findingScanner, type Finding, type FindingWorkflow, type ScanType } from '@drobon/shared';
import { redactAssistantText } from '../assistant/redaction.js';

/**
 * Source scanners emit one finding per scanner/rule/file/line. Their v2
 * identity never hashes evidence or raw source text, so redaction and
 * evidence wording changes do not split the same observed finding. Other
 * scanners retain v1 until they expose enough structured discriminators
 * to distinguish multiple findings at one location without guessing.
 */
export function findingFingerprint(options: {
  scanner: ScanType;
  projectId: string;
  ruleId: string;
  location: string;
  line?: number;
  evidence: string;
  context?: readonly string[];
}): string {
  const normalizedLocation = options.location.normalize('NFC').replace(/\\/g, '/');
  const common = [options.scanner, options.projectId, options.ruleId, normalizedLocation, options.line ?? null,
    ...(options.context ?? []).map((item) => item.normalize('NFC'))];
  if (options.scanner === 'SAST' || options.scanner === 'SECRETS') {
    return createHash('sha256').update(JSON.stringify(['drobon-finding-v2', ...common]), 'utf8').digest('hex');
  }
  const normalizedEvidence = options.evidence.normalize('NFC').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '');
  const evidenceDigest = createHash('sha256').update(normalizedEvidence, 'utf8').digest('hex');
  return createHash('sha256').update(JSON.stringify(['drobon-finding-v1', ...common, evidenceDigest]), 'utf8').digest('hex');
}

/** v2 comparison key for the bounded source scanners, including legacy rows. */
export function sourceFindingIdentity(finding: Finding, projectId: string): string | undefined {
  const scanner = findingScanner(finding);
  if ((scanner !== 'SAST' && scanner !== 'SECRETS') || finding.file === undefined || finding.line === undefined) return undefined;
  return findingFingerprint({ scanner, projectId, ruleId: finding.ruleId, location: finding.file, line: finding.line, evidence: '' });
}

/**
 * Source lines are untrusted and may contain unrelated, unknown or short
 * credentials. Detection rules decide whether a finding exists; they are
 * deliberately NOT used as an evidence allowlist. No general-purpose
 * scanner can prove an arbitrary source line is free of secrets, so the
 * safe projection keeps rule/location metadata but withholds the line.
 */
export const WITHHELD_SOURCE_EVIDENCE = '<redacted> (source snippet withheld; review the recorded location)';
export const WITHHELD_SENSITIVE_EVIDENCE = '<redacted> (sensitive evidence withheld; review under appropriate access controls)';

/** Legacy free-text rule metadata may contain recognized credentials too.
 * Preserve safe text and the finding's identity/location; bound replacements
 * so the projection still satisfies the public Finding contract. Detection is
 * heuristic, not a guarantee that arbitrary metadata is secret-free. */
function safeFindingText(value: string, maxLength: number): string {
  const checked = redactAssistantText(value);
  if (!checked.redacted && checked.safeForProvider) return value;
  // Withhold the complete field rather than re-running a replacement on an
  // already-redacted assignment (which would not be idempotent).
  return '<redacted> (sensitive text withheld)'.slice(0, maxLength);
}

export function safeFindingEvidence(finding: Finding): Finding {
  const scanner = findingScanner(finding);
  const projected: Finding = {
    ...finding,
    title: safeFindingText(finding.title, FINDING_TITLE_MAX_LENGTH),
    description: safeFindingText(finding.description, FINDING_TEXT_MAX_LENGTH),
    remediation: safeFindingText(finding.remediation, FINDING_TEXT_MAX_LENGTH),
  };
  if (scanner === 'SAST' || scanner === 'SECRETS') return { ...projected, evidence: WITHHELD_SOURCE_EVIDENCE };
  // Legacy DAST/SCA evidence was not necessarily generated by today's
  // bounded templates. Withhold the whole field if the existing recognizer
  // detects credentials. This is idempotent, but cannot recognize every
  // unknown secret; other free-text and location fields remain untrusted.
  const checked = redactAssistantText(finding.evidence);
  return checked.redacted || !checked.safeForProvider
    ? { ...projected, evidence: WITHHELD_SENSITIVE_EVIDENCE }
    : projected;
}

/** Defense in depth for legacy free-text notes; arbitrary prose cannot be
 * proven secret-free, so this is not a substitute for careful user input. */
export function safeFindingWorkflow(workflow: FindingWorkflow): FindingWorkflow {
  return {
    ...workflow,
    notes: workflow.notes.map((note) => {
      const safe = redactAssistantText(note.text);
      return { ...note, text: safe.safeForProvider ? safe.text : '[sensitive content omitted]', redacted: note.redacted || safe.redacted };
    }),
  };
}
