/**
 * Session cookie handling — the ONLY transport for session tokens.
 *
 * Cookie attributes (all three are load-bearing security controls):
 * - `HttpOnly`: JavaScript (including injected XSS payloads) can never
 *   read the token;
 * - `SameSite=Strict`: browsers do not attach the cookie to any
 *   cross-site request, which is the primary CSRF defense;
 * - `Secure` in production: the token never travels over plain HTTP once
 *   the app is deployed behind TLS (omitted on plain-HTTP localhost so
 *   development works without certificates).
 *
 * The value itself is an opaque base64url token generated by the session
 * store — no structure for clients to parse or forge.
 */

export const SESSION_COOKIE_NAME = 'drobon_session';

export interface CookieOptions {
  /** Add the `Secure` attribute (production only — see ApiConfig). */
  secure: boolean;
  /** Lifetime in seconds (aligned with the server-side session TTL). */
  maxAgeSeconds: number;
}

/** Build the `Set-Cookie` value for a freshly issued session. */
export function sessionCookie(token: string, options: CookieOptions): string {
  const parts = [
    `${SESSION_COOKIE_NAME}=${token}`,
    'Path=/',
    'HttpOnly',
    'SameSite=Strict',
    `Max-Age=${Math.max(0, Math.floor(options.maxAgeSeconds))}`,
  ];
  if (options.secure) {
    parts.push('Secure');
  }
  return parts.join('; ');
}

/** Build the `Set-Cookie` value that removes the session cookie. */
export function clearSessionCookie(options: { secure: boolean }): string {
  const parts = [
    `${SESSION_COOKIE_NAME}=`,
    'Path=/',
    'HttpOnly',
    'SameSite=Strict',
    'Max-Age=0',
    'Expires=Thu, 01 Jan 1970 00:00:00 GMT',
  ];
  if (options.secure) {
    parts.push('Secure');
  }
  return parts.join('; ');
}

/**
 * Parse a request `Cookie` header into a plain map. Values are not
 * URL-decoded on purpose: the session token we issue is base64url (no
 * decoding needed), and any other encoding simply fails to match a known
 * session — failure closed.
 */
export function parseCookies(header: string | undefined): Record<string, string> {
  const out: Record<string, string> = {};
  if (header === undefined || header.length === 0) {
    return out;
  }
  for (const part of header.split(';')) {
    const index = part.indexOf('=');
    if (index <= 0) {
      continue;
    }
    const name = part.slice(0, index).trim();
    if (name.length > 0 && !(name in out)) {
      out[name] = part.slice(index + 1).trim();
    }
  }
  return out;
}

/** Extract the session token from a request cookie header, if present. */
export function readSessionToken(cookieHeader: string | undefined): string | undefined {
  const token = parseCookies(cookieHeader)[SESSION_COOKIE_NAME];
  return token !== undefined && token.length > 0 ? token : undefined;
}
